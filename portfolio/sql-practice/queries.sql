    ROUND(100.0 * SUM(CASE WHEN age BETWEEN 11 AND 13 THEN 1 ELSE 0 END) / COUNT(*), 2) AS "11-13 лет, %",
    ROUND(100.0 * SUM(CASE WHEN age BETWEEN 14 AND 18 THEN 1 ELSE 0 END) / COUNT(*), 2) AS "14-18 лет, %",
    ROUND(100.0 * SUM(CASE WHEN age > 18 THEN 1 ELSE 0 END) / COUNT(*), 2) AS ">18 лет, %"
FROM v_age
GROUP BY brand
ORDER BY brand;

-- Определить завод-изготовитель, продукция которого больше других требует ремонта (гарантийный срок не учитывать) в абсолютных показателях и завод с наибольшей долей отказов продукции (число ремонтов на один зарегистрированный в базе данных автомобиль). Выдать наименования, принадлежность брендам, страны брендов, почтовые адреса и телефоны (в двух столбцах), количество ремонтов выпущенных ими автомобилей и долю ремонтов на один зарегистрированный автомобиль.
-- Ответ: по первому показателю завод "Волжский автомобильный завод ОАО АВТОВАЗ" с абсолютным показателем 163 отказа; по второму показателю завод "Austria Bavarischen motorwerke" с долей в 0.666667.
WITH factory_vehicles AS (
    SELECT
        f.idf,
        f.factory_name,
        COUNT(v.gnz) AS "vehicle_count"
    FROM factory f
    JOIN vehicle v ON v.idf = f.idf
    GROUP BY f.idf, f.factory_name
)
(
    SELECT
        f.factory_name AS "Завод",
        b.name AS "Бренд",
        s.name AS "Страна",
        b.post_addr AS "Адрес",
        b.phone AS "Телефон",
        COUNT(*) AS "Количество ремонтов",
        0 AS "Доля ремонтов"
    FROM maintenance m
    JOIN factory f ON f.idf = m.idf
    JOIN brand b ON b.idb = f.idb
    JOIN state s ON s.st_id = b.st_id
    GROUP BY f.factory_name, b.name, s.name, b.post_addr, b.phone
    ORDER BY COUNT(*) DESC
    LIMIT 1
)
UNION ALL
(
    SELECT
        f.factory_name AS "Завод",
        b.name AS "Бренд",
        s.name AS "Страна",
        b.post_addr AS "Адрес",
        b.phone AS "Телефон",
        COUNT(*) AS "Количество ремонтов",
        ROUND(fv.vehicle_count::numeric / COUNT(*), 6) AS "Доля ремонтов"
    FROM maintenance m
    JOIN factory f ON f.idf = m.idf
    JOIN brand b ON b.idb = f.idb
    JOIN state s ON s.st_id = b.st_id
    JOIN factory_vehicles fv ON fv.idf = f.idf
    GROUP BY f.factory_name, b.name, s.name, b.post_addr, b.phone, fv.vehicle_count
    ORDER BY fv.vehicle_count::numeric / COUNT(*) DESC
    LIMIT 1
);

-- Найти автомобили с заводским браком (интервал времени между датой регистрации и первым ремонтом, не превышающий 1 года). Выдать их государственные номерные знаки; производителя, марку и модель в одном столбце; дату регистрации; дату первого ремонта; интервал в днях от регистрации до первого ремонта.
-- Ответ: 3 автомобиля, два NISSAN и один ГАЗ.
WITH first_repair AS(
    SELECT
        m.gnz,
        m.date_work,
        ROW_NUMBER() OVER(PARTITION BY gnz ORDER BY date_work::date) AS rn
    FROM maintenance m
    JOIN maintenancetype mt ON mt.mt_id = m.mt_id
    WHERE mt.name ILIKE 'ремонт'
)
SELECT
    first_repair.gnz AS "Гос. номер",
    concat(b.name, ', ', ma.name, ', ', mo.model_name) AS "Автомобиль",
    to_char(v.date$reg_certif, 'dd.mm.yyyy') AS "Дата регистрации",
    to_char(first_repair.date_work, 'dd.mm.yyyy') AS "Дата ремонта",
    date_part('day', first_repair.date_work - v.date$reg_certif) AS "Дней до ремонта"
FROM first_repair
JOIN vehicle v ON first_repair.gnz = v.gnz
JOIN brand b ON b.idb = v.idb
JOIN marka ma ON ma.idm = v.idm
JOIN model mo ON mo.idmo = v.idmo
WHERE first_repair.rn = 1
  AND date_part('day', first_repair.date_work - v.date$reg_certif) < 366;

-- Найти автомобили, которые в течение одного года обслуживались или ремонтировались только у разных механиков. Выдать их государственные номерные знаки, даты, когда проводилось обслуживание или ремонт, фамилии и инициалы механиков. Учесть, что автомобили, посещавшие предприятие один раз в году, также относятся к обслуженным разными механиками в этом году, отсортировать выдачу по государственным номерным знакам.
-- Ответ: 340 строк, 3 столбца.
SELECT
    m.gnz AS "Гос. номер",
    me.sname_initials AS "Механик",
    to_char(m.date_work, 'dd.mm.yyyy') AS "Дата работы"
FROM maintenance m
JOIN mechanic me ON me.id_mech = m.id_mech
WHERE (m.gnz, date_part('year', m.date_work)) IN (
    SELECT
        gnz,
        date_part('year', date_work) AS "work_year"
    FROM maintenance
    GROUP BY gnz, date_part('year', date_work)
    HAVING COUNT(*) = COUNT(DISTINCT id_mech)
)
ORDER BY m.gnz, m.date_work;

-- Определить медианное значение и разброс стоимости зарегистрированных автомобилей, считая, что стоимость распределена нормально. Для определения медианного значения стоимости использовать математическое ожидание, рассчитанное, как сумма произведений каждой стоимости на количество ее повторов в ряду стоимостей, деленное на общее число зарегистрированных автомобилей. Разброс рассчитать, как квадратный корень из разности медианы ранжированного ряда квадратов стоимости и квадрата медианы.
-- Ответ: медиана – 2 290 301 руб., разброс – 3 932 362 руб.
-- Corrected terminology: the task describes a mean, not a sample median.
-- Return both statistics explicitly; do not hard-code the historical row count 161.
SELECT
    AVG(cost::numeric) AS "Средняя стоимость (по условию)",
    PERCENTILE_CONT(0.5) WITHIN GROUP (ORDER BY cost::numeric) AS "Медиана ряда",
    STDDEV_POP(cost::numeric) AS "Разброс (σ)"
FROM vehicle;
