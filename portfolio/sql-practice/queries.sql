-- Составить таблицу изменения рентабельности предприятия по годам, где показаны абсолютное число выполненных заказов, относительное число заказов на один зарегистрированный автомобиль (учесть, что после выполнения предпродажной подготовки, автомобиль более не является зарегистрированным, хотя данные о нем сохраняются в базе данных), абсолютный прирост числа заказов, упущенная выгода в виде не добранных процентов если считать за 100% ситуацию, когда все зарегистрированные автомобили прибывают на предприятие один раз в год.
-- Ответ: 25 строк, 4 столбца.
WITH orders_per_year AS (
  SELECT
    EXTRACT(YEAR FROM date_work)::int AS "year",
    COUNT(*) AS total_orders
  FROM maintenance
  GROUP BY 1
),
registered_by_year AS (
  SELECT "year"::int,
    (SELECT COUNT(*) FROM vehicle v
     WHERE EXTRACT(YEAR FROM date$reg_certif) <= "year"
       AND NOT EXISTS (
         SELECT 1 FROM maintenance m2
         JOIN maintenancetype mt ON m2.mt_id = mt.mt_id
         WHERE m2.gnz = v.gnz
           AND EXTRACT(YEAR FROM m2.date_work) <= "year"
           AND mt.name ILIKE '%предпродаж%'
       )
    ) AS registered_count
  FROM (SELECT DISTINCT "year" FROM orders_per_year) y
)
SELECT
  o.year AS "Год",
  o.total_orders AS "Число заказов",
  ROUND(o.total_orders::numeric / NULLIF(r.registered_count, 0), 4) AS "Заказов на авто",
  o.total_orders - LAG(o.total_orders) OVER (ORDER BY o.year) AS "Абсолютный прирост",
  ROUND((1 - o.total_orders::numeric / NULLIF(r.registered_count, 0)) * 100, 2) AS "Упущенная выгода, %"
FROM orders_per_year o
LEFT JOIN registered_by_year r ON o.year = r.year
ORDER BY o.year;

